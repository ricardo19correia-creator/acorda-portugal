/**
 * Obtém a lista de cidades válidas de um distrito
 */
export function getDistrictCities(districtName: string): string[] {
  if (!districtName) return []
  const canonical = VALID_DISTRICTS.find(
    (d) => d.toLowerCase() === districtName.toLowerCase().trim()
  )
  if (canonical && DISTRICT_CITIES_MAP[canonical]) {
    return DISTRICT_CITIES_MAP[canonical]
  }
  return []
}

/**
 * Valida se um distrito pertence aos 20 distritos oficiais
 */
export function isValidDistrict(districtName: string): boolean {
  if (!districtName) return false
  return VALID_DISTRICTS.some(
    (d) => d.toLowerCase() === districtName.toLowerCase().trim()
  )
}

/**
 * Retorna o nome canónico do distrito
 */
export function normalizeDistrict(districtName: string): ValidDistrict | '' {
  if (!districtName) return ''
  const found = VALID_DISTRICTS.find(
    (d) => d.toLowerCase() === districtName.toLowerCase().trim()
  )
  return found || ''
}

/**
 * Valida se uma cidade pertence ao distrito selecionado
 */
export function isValidCityForDistrict(districtName: string, cityName: string): boolean {
  if (!districtName || !cityName) return false
  const cities = getDistrictCities(districtName)
  return cities.some((c) => c.toLowerCase() === cityName.toLowerCase().trim())
}

/**
 * Obtém a cidade padrão (capital de distrito) para um distrito
 */
export function getDefaultCityForDistrict(districtName: string): string {
  const cities = getDistrictCities(districtName)
  return cities[0] || districtName
}
