export function getArenaDimensions(assetPathOrId?: string | null): ArenaDimensions {
  if (!assetPathOrId) return { width: 1376, height: 768, aspectRatio: 1.7917 }
  if (ARENA_DIMENSIONS[assetPathOrId]) return ARENA_DIMENSIONS[assetPathOrId]
  const match = ARENA_SHOP_CATALOG.find((a) => a.id.toLowerCase() === String(assetPathOrId).toLowerCase().trim())
  if (match && match.image && ARENA_DIMENSIONS[match.image]) return ARENA_DIMENSIONS[match.image]
  return { width: 1376, height: 768, aspectRatio: 1.7917 }
}

export function getOfficialArenaImage(arenaId: string): string {
  const normalizedId = String(arenaId).toLowerCase().trim()
  if (normalizedId in ARENA_IMAGES) {
    return ARENA_IMAGES[normalizedId]
  }
  const match = ARENA_SHOP_CATALOG.find((a) => a.id.toLowerCase() === normalizedId)
  if (match && match.image) return match.image
  return ARENA_SHOP_CATALOG[0].image || '/arenas/Terreiro Dourado.jpg'
}

export const getArenaRarityBadge = (rarity: ArenaRarity | string): string => {
  switch (rarity) {
    case 'Comum':
      return 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40'
    case 'Rara':
      return 'bg-cyan-500/20 text-cyan-300 border-cyan-500/40'
    case 'Épica':
      return 'bg-purple-500/20 text-purple-300 border-purple-500/40'
    case 'Lendária':
      return 'bg-amber-500/20 text-amber-300 border-amber-500/40 shadow-[0_0_10px_rgba(245,158,11,0.25)]'
    case 'Mítica':
    case 'Exclusiva':
      return 'bg-rose-500/20 text-rose-300 border-rose-500/50 shadow-[0_0_12px_rgba(244,63,94,0.35)]'
    default:
      return 'bg-slate-800 text-slate-300 border-slate-700'
  }
}

