/**
 * Funções utilitárias SSOT
 */
export function getVipProductById(id: string): VipProduct | undefined {
  if (!id) return undefined
  const cleaned = id.trim()
  return VIP_CATALOG.find((p) => p.id === cleaned || p.sku === cleaned)
}

export function getVipProductsByCategory(category: VipCategory): VipProduct[] {
  return VIP_CATALOG.filter((p) => p.category === category)
}

export function getAllVipProducts(): VipProduct[] {
  return VIP_CATALOG
}

export function formatVipPrice(priceCents: number): string {
  const euros = (priceCents / 100).toFixed(2).replace('.', ',')
  return `€${euros}`
}
